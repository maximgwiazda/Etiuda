// The 2.x build: modules in src/, one readable HTML file at engine/etiuda.html.
//
//   node tools/build.mjs
//
// Two sources go in. `src/template.html` is the document with the app script's body replaced
// by one anchor, and `src/main.js` is the module tree, bundled into that anchor. There is no
// third: the extraction finished on 2026-09-14 and src/monolith.js is gone, so the anchor now
// takes the bundle alone and the app starts on the bundle's last line.
//
// The build options are `bundler-probe`'s, unchanged, so the conditions spec 9 binds are proved
// by that probe rather than restated here.
import { existsSync, lstatSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';
import { OPTIONS } from './bundler-probe/build.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const SRC = join(ROOT, 'src');
export const OUT_FILE = join(ROOT, 'engine', 'etiuda.html');
export const PIN_FILE = join(ROOT, 'engine', 'etiuda.csp.json');
// The bubble, published on its own so a second program renders the family from these bytes
// rather than from a copy of them. See bubbleCss() below.
export const CSS_FILE = join(ROOT, 'engine', 'bubble.css');
// The files a reader of the page needs. tests/build-fresh.mjs reads this list rather than one of
// its own, so a new output cannot be added here and left outside the freshness gate.
// The build record is a fourth file, written beside these and left out of this list on purpose:
// it is gitignored, and the freshness gate compares committed bytes.
export const OUTPUTS = [OUT_FILE, PIN_FILE, CSS_FILE];
export const RECORD_FILE = join(ROOT, 'engine', 'etiuda.build.json');
const ANCHOR = '/*@APP*/\n';
const BUB_BEGIN = '/*@BUBBLE-BEGIN*/\n', BUB_END = '/*@BUBBLE-END*/\n';

const sha256 = s => createHash('sha256').update(s, 'utf8').digest('hex');

// The shell serves this artifact under a content security policy whose script-src names the
// inline scripts by hash. Hashing at SERVE time would hash whatever the file then held, so a
// script edited into the artifact would be hashed along with the rest and would run. Hashing
// here pins the list to what the build produced, and a later edit is a script the policy does
// not name. A JSON block is skipped: application/json is data the browser never runs.
export function scriptHashes(html) {
  const re = /<script(?![^>]*\ssrc=)([^>]*)>([\s\S]*?)<\/script>/gi;
  const out = [];
  let m;
  while ((m = re.exec(html)) !== null) {
    if (/type\s*=\s*["']?application\/json/i.test(m[1])) continue;
    out.push("'sha256-" + createHash('sha256').update(m[2], 'utf8').digest('base64') + "'");
  }
  return out;
}

// THE BUBBLE IS EXTRACTED, NOT ASSEMBLED, and the direction is the whole point. The sheet stays
// one file, so tests/css-layers.js and tests/css-order.js still judge the family against every
// rule it can meet; a partial included INTO the template would have carried those rules out of
// the only two gates that watch a tie or a layer move. What Studio links is a copy that a build
// makes, and a copy a build makes cannot drift from what it was copied from.
function bubbleCss(template) {
  const a = template.indexOf(BUB_BEGIN), b = template.indexOf(BUB_END);
  const nb = template.split(BUB_BEGIN).length - 1, ne = template.split(BUB_END).length - 1;
  if (nb !== 1 || ne !== 1)
    throw new Error('the template holds ' + nb + ' bubble begin markers and ' + ne + ' end markers, expected 1 of each');
  if (b < a) throw new Error('the bubble end marker sits before its begin marker');
  const body = template.slice(a + BUB_BEGIN.length, b);
  if (!/\.bub-tip\s*\{/.test(body) || !/\.bub\s*\{/.test(body))
    throw new Error('the marked bubble span has lost .bub or .bub-tip; it is not the family any more');
  return '/* Etiuda - the bubble. Copyright (c) 2026 Maxim Gwiazda, Etiuda Source-Available\n'
       + '   Licence 1.0, LICENSE at the root of this repository.\n'
       + '   GENERATED by tools/build.mjs from the marked span of src/template.html. Edit it\n'
       + '   there. A host page owes this file the tokens the span names. */\n' + body;
}

// WHAT THE SOURCE CANNOT KNOW, written into the bundle over string literals that src/ holds once
// each: the day of the build, and the end-user agreement from the installer's own files, so the
// program shows the text the installer showed and needs no connection to show it.
const BUILT_SLOT = '"@E_BUILT@"';
const EULA_SLOTS = [['"@EULA_EN@"', 'license_en.txt'], ['"@EULA_PL@"', 'license_pl.txt']];

function once(bundle, slot) {
  const hits = bundle.split(slot).length - 1;
  if (hits !== 1) throw new Error(slot + ' matched ' + hits + ' times in the bundle, expected 1');
  return bundle;
}
const fill = (bundle, slot, value) => once(bundle, slot).split(slot).join(value);
// A string literal inside an inline script, so a `<` is escaped and no text can close the script.
function agreement(name) {
  const text = readFileSync(join(ROOT, 'shell', name), 'utf8').replace(/^\ufeff/, '').replace(/\r\n/g, '\n');
  return JSON.stringify(text).split('<').join('\\u003c');
}
const today = () => {
  const d = new Date(), p = n => String(n).padStart(2, '0');
  return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate());
};
/** The day an artefact says it was built, or null. */
export function builtStamp(html) {
  const m = /\bE_BUILT = "(\d{4}-\d\d-\d\d)";/.exec(html || '');
  return m ? m[1] : null;
}
/* THE DAY MOVES WITH THE BUILD'S CONTENT. A rebuild that would change nothing but the date keeps
   the date it finds, so an unchanged tree builds byte for byte (tests/build-fresh.mjs depends on
   it); anything else takes today. */
export function stampFor(previous, htmlAt, day) {
  const kept = builtStamp(previous);
  return kept && htmlAt(kept) === previous ? kept : day;
}

/* A day the caller handed in. Empty is the same as absent. Anything else that is not a real
   calendar day is refused before a single file is written, and the value itself is not repeated. */
export function calendarDay(s) {
  if (typeof s !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(s)) return false;
  const y = +s.slice(0, 4), m = +s.slice(5, 7), d = +s.slice(8, 10);
  const dt = new Date(Date.UTC(y, m - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === m - 1 && dt.getUTCDate() === d;
}
export function handedDay() {
  const raw = process.env.ETIUDA_BUILD_DAY;
  if (raw === undefined || raw === '') return null;
  if (!calendarDay(raw)) throw new Error('ETIUDA_BUILD_DAY is not a day (YYYY-MM-DD); nothing was written'); /* plant:build-day */
  return raw;
}

/* What a clean tree is judged on. A change outside this list does not move the day. A change
   to a file's time alone is not a change: git status is the record. */
export const INPUTS = [
  'src',
  'tools/build.mjs',
  'tools/bundler-probe/build.mjs',
  'shell/license_en.txt',
  'shell/license_pl.txt',
];

export const COMMIT_DAY = 'ETIUDA_BUILD_COMMIT_DAY';
/* Off unless ETIUDA_BUILD_COMMIT_DAY is exactly 1. On, the day is the committer date the
   commit records (git log -1 --format=%cs). That recorded date does not depend on the
   machine's time zone, and a shallow clone reads the same day. Today is used only when an
   input is uncommitted. A tree with no repository takes the handed-in day, or today. */
export function commitDayOn() {
  return process.env[COMMIT_DAY] === '1';
}

function gitOut(args) {
  try {
    const out = execFileSync('git', args, {
      cwd: ROOT,
      encoding: 'utf8',
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return { ok: true, out: out || '' };
  } catch (e) {
    const err = String((e && e.stderr) || '') + String((e && e.message) || '');
    const noRepo = !!(e && (e.status === 128 || /not a git repository/i.test(err)));
    return { ok: false, noRepo, err };
  }
}

/* null when this folder is not a repository, true when an input differs from the commit. */
export function inputsDirty() {
  const st = gitOut(['status', '--porcelain', '--untracked-files=all', '--', ...INPUTS]);
  if (!st.ok) {
    if (st.noRepo) return null;
    throw new Error('the build could not read git status; nothing was written');
  }
  return st.out.trim() !== '';
}

function committerDay() {
  const r = gitOut(['log', '-1', '--format=%cs']);
  if (!r.ok) return null;
  const line = r.out.trim();
  return calendarDay(line) ? line : null;
}

function dayUnhanded(previous, htmlAt) {
  if (!commitDayOn()) return stampFor(previous, htmlAt, today());
  const dirty = inputsDirty();
  if (dirty === null || dirty === true) return today();
  return committerDay() || today();
}

function dayFor(previous, htmlAt) {
  const handed = handedDay();
  if (handed) return handed;
  return dayUnhanded(previous, htmlAt);
}

/* One digest of every input, in path order. A symlink is not walked, so a link cannot add a
   directory the tree did not mean to hash. The bytes are the file's own, and the path is a
   forward-slash path from the repository root. */
function inputFiles() {
  const found = [];
  const walk = rel => {
    const abs = join(ROOT, ...rel.split('/'));
    const st = lstatSync(abs);
    if (st.isSymbolicLink()) return;
    if (st.isDirectory()) {
      for (const ent of readdirSync(abs, { withFileTypes: true })) {
        if (ent.isSymbolicLink()) continue;
        const child = rel + '/' + ent.name;
        if (ent.isDirectory()) walk(child);
        else if (ent.isFile()) found.push(child);
      }
      return;
    }
    if (st.isFile()) found.push(rel);
  };
  for (const rel of INPUTS) walk(rel.split('\\').join('/'));
  found.sort();
  return found;
}
function inputDigest() {
  const h = createHash('sha256');
  for (const rel of inputFiles()) {
    const body = readFileSync(join(ROOT, ...rel.split('/')));
    h.update(rel + '\0' + createHash('sha256').update(body).digest('hex') + '\n', 'utf8');
  }
  return h.digest('hex');
}

/* Whether the three outputs are this source at the day a build now would stamp. File times are
   not read. A second bundle is not built: when the input digest matches and the page's stamp
   matches the record, that stamp is the day, unless a handed-in day or the commit-day switch
   names a different one. */
export function outputsCurrent() {
  try {
    for (const file of OUTPUTS) if (!existsSync(file)) return false;
    let record;
    try { record = JSON.parse(readFileSync(RECORD_FILE, 'utf8')); }
    catch { return false; }
    if (!record || record.kind !== 'etiuda-build-record' || record.schema !== 1) return false;
    if (typeof record.day !== 'string' || typeof record.inputs !== 'string') return false;
    if (record.inputs !== inputDigest()) return false;
    let html = '';
    try { html = readFileSync(OUT_FILE, 'utf8'); } catch { return false; }
    if (builtStamp(html) !== record.day) return false;
    let handed = null;
    try { handed = handedDay(); } catch { return false; }
    if (handed) return handed === record.day;
    if (!commitDayOn()) return true;
    const dirty = inputsDirty();
    const day = (dirty === null || dirty === true) ? today() : (committerDay() || today());
    return day === record.day;
  } catch {
    return false;
  }
}

// LF in this tree. A CR reaching the artifact would report as every line changed in the next
// diff, so it is refused at the source rather than explained afterwards.
function read(name) {
  const text = readFileSync(join(SRC, name), 'utf8');
  if (text.includes('\r')) throw new Error('src/' + name + ' holds a CR byte; this tree is LF');
  return text;
}

export async function build() {
  const t0 = Date.now();
  handedDay();
  // absWorkingDir pins the module banners esbuild writes above each module to paths relative to
  // this repository. Without it they are relative to the caller's directory, and this artifact
  // is published.
  const result = await esbuild.build({ ...OPTIONS, absWorkingDir: ROOT, entryPoints: [join(SRC, 'main.js')] });
  if (result.outputFiles.length !== 1)
    throw new Error('esbuild emitted ' + result.outputFiles.length + ' files; the artifact is one file');
  let bundle = result.outputFiles[0].text;
  if (bundle.includes('\r')) throw new Error('the bundle holds a CR byte');
  for (const [slot, name] of EULA_SLOTS) bundle = fill(bundle, slot, agreement(name));
  once(bundle, BUILT_SLOT);

  const template = read('template.html');
  const hits = template.split(ANCHOR).length - 1;
  if (hits !== 1) throw new Error(ANCHOR.trim() + ' matched ' + hits + ' times in the template, expected 1');

  // split/join rather than replace: the engine's own text holds `$&` and `$1`, which a
  // replacement string would substitute rather than copy.
  const htmlAt = day => template.split(ANCHOR).join(bundle.split(BUILT_SLOT).join(JSON.stringify(day)));
  let previous = '';
  try { previous = readFileSync(OUT_FILE, 'utf8'); } catch { /* a first build */ }
  const day = dayFor(previous, htmlAt);
  const html = htmlAt(day);
  if (builtStamp(html) !== day) throw new Error('the build day ' + day + ' cannot be read back out of the artifact');
  const inputs = inputDigest();
  writeFileSync(OUT_FILE, html, 'utf8');
  const hashes = scriptHashes(html);
  if (hashes.length !== 2)
    throw new Error('the artifact holds ' + hashes.length + ' inline scripts; the policy expects 2');
  writeFileSync(PIN_FILE, JSON.stringify({ kind: 'etiuda-script-hashes', schema: 1, hashes }) + '\n', 'utf8');
  const css = bubbleCss(template);
  writeFileSync(CSS_FILE, css, 'utf8');
  writeFileSync(RECORD_FILE, JSON.stringify({
    kind: 'etiuda-build-record', schema: 1, day, inputs,
  }) + '\n', 'utf8');
  return { bytes: Buffer.byteLength(html, 'utf8'), bundleBytes: Buffer.byteLength(bundle, 'utf8'),
           cssBytes: Buffer.byteLength(css, 'utf8'),
           sha256: sha256(html), hashes, ms: Date.now() - t0 };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const before = (() => { try { return sha256(readFileSync(OUT_FILE, 'utf8')); } catch { return '(absent)'; } })();
    const r = await build();
    console.log('engine/etiuda.html  ' + r.bytes + ' bytes, ' + r.bundleBytes + ' of them the bundle, ' + r.ms + ' ms');
    console.log('  was ' + before.slice(0, 16));
    console.log('  now ' + r.sha256.slice(0, 16));
    console.log('engine/etiuda.csp.json  ' + r.hashes.length + ' pinned script hash(es)');
    console.log('engine/bubble.css  ' + r.cssBytes + ' bytes');
  } catch (e) {
    console.error(e && e.message ? e.message : String(e));
    process.exit(1);
  }
}
